#!/usr/bin/env python3
"""
Generate the ready-to-run config files for the Paper 9 multi-seed campaign.

Reads test_tools/paper9_multiseed_base.yaml (the fixed protocol) and stamps, per run:
  - random_seed
  - env_params.communication.strategy   (Tier A: naive_broadcast=S0 / uaq=S1)
  - env_params.communication.strategies (Tier B: [] / [federated_sync] / ...)
  - env_params.communication.uaq.tau    (only for the tau=0.9 probe)

Writes config/marl_pz/tier1/<cell>__seed<NN>.yaml (and tier2/).
Each output file is a complete, standalone config: copy it to config/default.yaml
and launch, or import it from the web UI.

Usage:
    python3 test_tools/gen_paper9_multiseed_configs.py            # writes tier1 + tier2
    python3 test_tools/gen_paper9_multiseed_configs.py --seeds 10 14 21 42 77
    python3 test_tools/gen_paper9_multiseed_configs.py --tier1-only
"""
import argparse
import copy
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BASE = os.path.join(HERE, "paper9_multiseed_base.yaml")
OUT_ROOT = os.path.join(ROOT, "config", "marl_pz")

DEFAULT_SEEDS = [10, 14, 77]  # matches the existing S2+S3 / S3+S4 multi-seed probes

# cell key -> (Tier A strategy, Tier B strategies list, extra env_params.communication patch)
TIER1 = {
    "s0":        ("naive_broadcast", [],                  {}),
    "s1":        ("uaq",             [],                  {}),
    "s0_s2":     ("naive_broadcast", ["federated_sync"],  {}),
    "s1_s2":     ("uaq",             ["federated_sync"],  {}),
    "s0_s4":     ("naive_broadcast", ["experience_sharing"], {}),
    "s1_s4":     ("uaq",             ["experience_sharing"], {}),
    "s0_s3":     ("naive_broadcast", ["policy_exchange"], {}),
    "s1_s3":     ("uaq",             ["policy_exchange"], {}),
}

TIER2 = {
    # S2+S4 both channels — resolve "substitutes vs. synergy" (currently single-seed)
    "s0_s2_s4":  ("naive_broadcast", ["federated_sync", "experience_sharing"], {}),
    "s1_s2_s4":  ("uaq",             ["federated_sync", "experience_sharing"], {}),
    # tau=0.9 UAQ-alone — the "lower overhead AND equal/better F1" lead, needs seeds
    "s1_tau09":  ("uaq",             [],                  {"uaq": {"tau": 0.9}}),
    # SARSA coverage of the two combos already multi-seeded for QL (base enables SARSA)
    "s1_s2_s3":  ("uaq",             ["federated_sync", "policy_exchange"], {}),
    "s0_s3_s4":  ("naive_broadcast", ["policy_exchange", "experience_sharing"], {}),
}

CELL_LABEL = {
    "s0": "S0 (naive broadcast, no Tier B)",
    "s1": "S1 (UAQ tau=0.8, no Tier B)",
    "s0_s2": "S0 + S2 federated_sync",
    "s1_s2": "S1 + S2 federated_sync",
    "s0_s4": "S0 + S4 experience_sharing",
    "s1_s4": "S1 + S4 experience_sharing",
    "s0_s3": "S0 + S3 policy_exchange",
    "s1_s3": "S1 + S3 policy_exchange",
    "s0_s2_s4": "S0 + S2 + S4",
    "s1_s2_s4": "S1 + S2 + S4",
    "s1_tau09": "S1 UAQ, tau=0.9, no Tier B",
    "s1_s2_s3": "S1 + S2 + S3 (SARSA coverage; QL already multi-seed)",
    "s0_s3_s4": "S0 + S3 + S4 (SARSA coverage; QL already multi-seed)",
}


def _apply_comm_patch(comm: dict, patch: dict) -> None:
    for k, v in patch.items():
        if isinstance(v, dict) and isinstance(comm.get(k), dict):
            comm[k].update(v)
        else:
            comm[k] = v


def build(base: dict, seed: int, strategy: str, strategies: list, patch: dict) -> dict:
    cfg = copy.deepcopy(base)
    cfg["random_seed"] = seed
    comm = cfg["env_params"]["communication"]
    comm["strategy"] = strategy
    comm["strategies"] = list(strategies)
    _apply_comm_patch(comm, patch)
    return cfg


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, nargs="+", default=DEFAULT_SEEDS)
    ap.add_argument("--tier1-only", action="store_true")
    args = ap.parse_args()

    with open(BASE) as fh:
        base = yaml.safe_load(fh)

    groups = {"tier1": TIER1}
    if not args.tier1_only:
        groups["tier2"] = TIER2

    total = 0
    lines = ["# Paper 9 multi-seed campaign — run matrix", "",
             f"Seeds: {args.seeds}", ""]
    for gname, cells in groups.items():
        out_dir = os.path.join(OUT_ROOT, gname)
        os.makedirs(out_dir, exist_ok=True)
        lines.append(f"## {gname}  ({len(cells)} cells x {len(args.seeds)} seeds "
                     f"= {len(cells) * len(args.seeds)} runs)")
        lines.append("")
        for cell, (strategy, strategies, patch) in cells.items():
            for seed in args.seeds:
                cfg = build(base, seed, strategy, strategies, patch)
                fname = f"{cell}__seed{seed}.yaml"
                with open(os.path.join(out_dir, fname), "w") as fh:
                    fh.write(f"# {CELL_LABEL.get(cell, cell)} | seed {seed}\n")
                    fh.write("# generated by test_tools/gen_paper9_multiseed_configs.py "
                             "-- edit test_tools/paper9_multiseed_base.yaml or the script\n")
                    yaml.dump(cfg, fh, sort_keys=False, default_flow_style=False)
                total += 1
            lines.append(f"- `{cell}` — {CELL_LABEL.get(cell, cell)} "
                         f"-> Tier A `{strategy}`, Tier B `{strategies or '[]'}`")
        lines.append("")

    lines.append(f"**Total: {total} runs** "
                 f"(each run trains Q-Learning + SARSA on the same scenario).")
    with open(os.path.join(OUT_ROOT, "RUN_MATRIX.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")

    print("\n".join(lines))
    print(f"\nWrote {total} config files under {OUT_ROOT}/")


if __name__ == "__main__":
    main()
