# sequential blue ramp (dataviz skill palette.md steps 200 / 450 / 650): topology
# size is an ordered magnitude, so one hue light->dark is the correct encoding.
COLORS = {"N10": "#9ec5f4", "N20": "#2a78d6", "N40": "#104281"}


def raw(run, agent):
    p = f"{BASE}/{run}/TEST_{agent}/test.json"
    if not os.path.exists(p):
        return None
    d = json.load(open(p))
    if agent not in d.get("predicted", {}):
        return None
    gt = np.array(d["ground_truth"], dtype=int)
    pr = np.array(d["predicted"][agent], dtype=int)
    return gt, pr


def macro(run, agent):
    r = raw(run, agent)
    if r is None:
        return None
    gt, pr = r
    return f1_score(gt, pr, average="macro", labels=[0, 1, 2], zero_division=0)


def cell_vals(topo_map, cell, agent, from_registry=False):
    if from_registry:
        seeds = REGISTRY[cell].seeds
    else:
        seeds = topo_map[cell]
    vals = []
    for seed in sorted(seeds):
        m = macro(seeds[seed], agent)
        if m is not None:
            vals.append(m)
    return np.array(vals)


def pooled_recall(topo_map, agent, from_registry=False):
    all_gt, all_pr = [], []
    for cell in CELLS:
        seeds = REGISTRY[cell].seeds if from_registry else topo_map[cell]
        for seed in sorted(seeds):
            r = raw(seeds[seed], agent)
            if r is None:
                continue
            gt, pr = r
            all_gt.append(gt)
            all_pr.append(pr)
    gt = np.concatenate(all_gt)
    pr = np.concatenate(all_pr)
    P, R, F, S = precision_recall_fscore_support(gt, pr, labels=[0, 1, 2], zero_division=0)
    return R, S


def make_f1_figure():
    fig, axes = plt.subplots(2, 1, figsize=(11, 8.4), sharex=True)
    x = np.arange(len(CELLS), dtype=float)
    w = 0.26
    for ax, agent, title in [(axes[0], QL, "Q-LEARNING"), (axes[1], SARSA, "SARSA")]:
        for i, (topo, from_reg) in enumerate([("N10", True), ("N20", False), ("N40", False)]):
            tmap = None if from_reg else (N20 if topo == "N20" else N40)
            means, sds = [], []
            for cell in CELLS:
                vals = cell_vals(tmap, cell, agent, from_registry=from_reg)
                means.append(vals.mean())
                sds.append(vals.std(ddof=1) if len(vals) > 1 else 0.0)
            offset = (i - 1) * w
            ax.bar(x + offset, means, w, yerr=sds, capsize=3, color=COLORS[topo],
                   edgecolor="black", linewidth=0.5, label=f"{topo[0]}={topo[1:]}"
                   .replace("N", "N=") if False else {"N10": "N=10", "N20": "N=20", "N40": "N=40"}[topo])
        ax.set_xticks(x)
        ax.set_xticklabels([CELL_LABEL[c] for c in CELLS])
        ax.set_ylim(0, 1.0)
        ax.set_ylabel("Macro-F1")
        ax.set_title(title, fontsize=11, fontweight="bold", loc="left")
        ax.grid(axis="y", linestyle="--", alpha=0.3)
    axes[0].legend(loc="upper left", ncol=3, frameon=False, fontsize=9)
    fig.suptitle("Zero-shot topology transfer, multi-seed (n=3, seeds 10/14/77):\n"
                 "macro-F1 at N=10 (native) vs. N=20 vs. N=40 (transfer)", fontsize=12.5)
    fig.tight_layout(rect=(0, 0, 1, 0.93))
