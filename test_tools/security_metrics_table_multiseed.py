#!/usr/bin/env python3
"""Multi-seed version of security_metrics_table.py's operational IPS metrics.

Unlike macro-F1 or a static confusion matrix, these metrics are computed over
*temporal* attack windows within one continuous per-host trace (see the module
docstring in security_metrics_table.py) -- concatenating raw arrays across seeds
would create a fake window spanning two unrelated traces. So each seed is scored
independently with the existing collect() (unmodified), and the three seeds'
per-metric values are aggregated as mean +/- sample s.d., the same convention used
throughout the paper9 multi-seed campaign (see paper9_multiseed.py).

The paper no longer \input's this table: its LaTeX is pasted directly into
experiments9.tex's Section~\ref{sec:exp_ips}. Re-running this script writes a
fresh standalone .tex snippet to --output-dir (default: a scratch dir) for you
to manually paste back in, replacing the existing \begin{table}...\end{table}
block there.

Usage:
    python3 test_tools/security_metrics_table_multiseed.py \
        --output-dir /tmp/p9_security_metrics
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from security_metrics_table import COLS, _fmt, collect  # noqa: E402
from paper9_multiseed import REGISTRY  # noqa: E402

# collect() (security_metrics_table.py) keys its output by the *normalized*
# algorithm name (normalize_algorithm_name), not the run-directory agent name
# ("Q-learning_quick"/"Sarsa_balanced") that paper9_multiseed.py's QL/SARSA
# constants use -- keep these separate from that module's constants.
QL, SARSA = "Q-Learning", "SARSA"
AGENT_LABEL = {QL: "Q-Learning", SARSA: "SARSA"}
# Cell ids and their paper labels, in the order the primary+secondary tables use.
CELLS = [
    "s0", "s0_s2", "s0_s3", "s0_s4", "s0_s2_s4",
    "s1", "s1_s2", "s1_s3", "s1_s4", "s1_s2_s4",
    "s1_tau09", "s1_s2_s3", "s0_s3_s4",
]


def aggregate(cell_id: str, agent: str) -> dict | None:
    cell = REGISTRY[cell_id]
    per_seed = []
    for seed in sorted(cell.seeds):
        run_dir = f"_training/marl_pz/{cell.seeds[seed]}"
        m = collect(run_dir, excluded=set()).get(agent)
        if m is not None:
            per_seed.append(m)
    if not per_seed:
        return None
    out = {}
    for key, _ in COLS:
        vals = np.array([m[key] for m in per_seed], dtype=float)
        vals = vals[~np.isnan(vals)]
        out[key] = (float(vals.mean()), float(vals.std(ddof=1)) if len(vals) > 1 else 0.0)
    out["n_seeds"] = len(per_seed)
    out["n_windows"] = [m["n_windows"] for m in per_seed]
    return out


def fmt_cell(mean, sd, nd=3):
    if np.isnan(mean):
        return "--"
    if sd == 0:
        return _fmt(mean, nd)
    return rf"{mean:.{nd}f}$\pm${sd:.{nd}f}"


def write_latex(rows, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "security_metrics_ips.tex"
    header = " & ".join(["Cell", "Alg."] + [c[1] for c in COLS]) + r" \\"
    lines = [
        "% generated by test_tools/security_metrics_table_multiseed.py -- do not edit by hand",
        r"\begin{table}[htbp]",
        r"    \centering",
        r"    \tiny",
        r"    \setlength{\tabcolsep}{3.2pt}",
        r"    \begin{tabular}{@{}ll" + "c" * len(COLS) + r"@{}}",
        r"        \toprule",
        "        " + header,
        r"        \midrule",
    ]
    for label, algo, m in rows:
        # REGISTRY labels use a literal Greek tau (matplotlib renders it fine) --
        # LaTeX under plain inputenc needs the macro form instead.
        tex_label = label.replace("τ", r"$\tau$")
        cells = " & ".join(
            fmt_cell(*m[k], nd=1 if k == "median_ttm" else 3) for k, _ in COLS
        )
        lines.append(f"        {tex_label} & {algo} & {cells} " + r"\\")
    lines += [
        r"        \bottomrule",
        r"    \end{tabular}",
        r"    \caption{Operational detection/mitigation, multi-seed (mean $\pm$ sample "
        r"s.d.\ over seeds 10/14/77, $n=3$; a bare number means $\mathrm{sd}=0$), "
        r"recomputed per-seed from the per-host \texttt{ground\_truth}/\texttt{predicted} "
        r"traces of Sections~\ref{sec:exp_baseline}--\ref{sec:exp_tier_b} (an "
        r"\textsc{attacker} label is an actual OVS flow-drop; each seed's 300 evaluation "
        r"episodes form one continuous per-host trace, so metrics are computed per seed "
        r"and then aggregated, not pooled). \emph{Neutralized}: fraction of attacker "
        r"host-steps blocked. \emph{TTM}: median episodes from attack onset to the "
        r"first block. \emph{Exposure}: attacker-active episodes with no block "
        r"asserted, over all attacker-active episodes. \emph{Block hold}: after the "
        r"first block, fraction of the remaining attack window still blocked. "
        r"\emph{Collateral}: benign host-steps blocked. \emph{Block prec.}: fraction "
        r"of issued blocks that hit a real attacker.}",
        r"    \label{tab:security_metrics_ips}",
        r"\end{table}",
    ]
    path.write_text("\n".join(lines) + "\n")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output-dir", default="/tmp/p9_security_metrics")
    args = ap.parse_args()

    rows = []
    hdr = (f"\n{'cell':<12}{'alg':<11}{'neutr':>16}{'medTTM':>14}{'expos':>16}"
           f"{'hold':>16}{'collat':>16}{'blkPrc':>16}  windows/seed")
    print(hdr)
    for cid in CELLS:
        for agent in (QL, SARSA):
            m = aggregate(cid, agent)
            if m is None:
                continue
            label = REGISTRY[cid].label
            rows.append((label, AGENT_LABEL[agent], m))
            print(f"{label:<12}{AGENT_LABEL[agent]:<11}"
                  f"{fmt_cell(*m['attacker_recall']):>16}"
                  f"{fmt_cell(*m['median_ttm'], nd=1):>14}"
                  f"{fmt_cell(*m['attacker_exposure']):>16}"
                  f"{fmt_cell(*m['post_block_hold']):>16}"
                  f"{fmt_cell(*m['collateral_block_rate']):>16}"
                  f"{fmt_cell(*m['block_precision']):>16}  {m['n_windows']}")

    out_dir = Path(args.output_dir)
    tex = write_latex(rows, out_dir)
    (out_dir / "security_metrics_ips.json").write_text(
        json.dumps(
            [{"cell": l, "algorithm": a, **{k: v for k, v in m.items() if k != "n_windows"},
              "n_windows_per_seed": m["n_windows"]} for l, a, m in rows],
            indent=2) + "\n"
    )
    print(f"\nwrote {tex}\nwrote {out_dir / 'security_metrics_ips.json'}")


if __name__ == "__main__":
    main()
